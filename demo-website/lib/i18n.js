/** Build a `t()` for one language, falling back to English then to the key. */
function translator(lang) {
  const primary = strings[lang] || strings[DEFAULT_LANG];
  const fallback = strings[DEFAULT_LANG];
  return (key, vars) => {
    let s = primary[key];
    if (s === undefined) s = fallback[key];
    if (s === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };
}

/** Prefix a path with the language segment ("/de/..." for German). */
function localePath(lang, urlPath = "/") {
  const clean = urlPath.startsWith("/") ? urlPath : `/${urlPath}`;
  if (lang === DEFAULT_LANG) return clean;
  return clean === "/" ? `/${lang}` : `/${lang}${clean}`;
}

/** Split "/de/courses/x" into { lang, path } */
function splitLocale(urlPath) {
  const m = /^\/(de)(\/.*)?$/.exec(urlPath);
  if (!m) return { lang: DEFAULT_LANG, path: urlPath || "/" };
  return { lang: m[1], path: m[2] || "/" };
}

